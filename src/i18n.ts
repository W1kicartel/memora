/** Translate `key` for `lang`, interpolating `{param}` tokens; falls back to EN then the key. */
export function translate(lang: Lang, key: string, params?: TParams): string {
  const s = TR[lang]?.[key] ?? TR.en[key] ?? key;
  return params ? s.replace(/\{(\w+)\}/g, (_, k) => String(params[k] ?? `{${k}}`)) : s;
}

export const LangContext = createContext<Lang>("it");

/** Hook: a translator bound to the active language from context. */
export function useT(): TFn {
  const lang = useContext(LangContext);
  return (key, params) => translate(lang, key, params);
}
